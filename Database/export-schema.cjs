// Offline exporter: executes migration builders against a collector, never SQL.
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  for (const [source, destination] of [
    ['001_initial.cjs', '001_new_database_only.sql'],
    ['002_setup_and_evidence.cjs', '002_optional_setup_new_database_only.sql']
  ]) {
    const batches = [];
    await require(path.join(__dirname, '..', 'Migrations', source)).up({
      raw: async sql => { batches.push(sql.trim()); }
    });
    const header = '-- Generated by Database/export-schema.cjs; no database connection is used.\n' +
      '-- Apply once in a new dedicated chatbot database, in numeric order.\n' +
      '-- Do not run over an existing installation. See Database/README.txt.\n' +
      '-- This does not create or replace dbo.usp_VerifyPatientIdentity.\n\n';
    // Qualify original unqualified CREATE/REFERENCES statements for logins whose
    // default schema is not dbo; all application queries explicitly use dbo.
    const sql = batches.map(batch => batch
      .replace(/CREATE TABLE (sessions|messages|events|verification_attempts|incidents|escalations|client_policy)\b/g, 'CREATE TABLE dbo.$1')
      .replace(/REFERENCES sessions\(/g, 'REFERENCES dbo.sessions(')
      .replace(/ ON (sessions|messages|escalations)\(/g, ' ON dbo.$1('))
      .join('\nGO\n\n');
    fs.writeFileSync(path.join(__dirname, destination), header + sql + '\nGO\n');
    console.log(`Exported ${destination} (${batches.length} SQL batches).`);
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
